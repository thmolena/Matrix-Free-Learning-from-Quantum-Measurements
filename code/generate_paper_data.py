# Experiment 1: Qubit inverse problem
# ============================================================

def generate_exp1_data(seed=42):
    """Generate qubit inverse problem data files.

    Produces:
      - cptp_qst_qubit_observables.dat  (exact, CPTP-fit, baseline-fit traces)
      - cptp_qst_qubit_noisy.dat        (noisy measurement data)
      - cptp_qst_sparse_ablation.dat    (multi-seed sparse-observation ablation)
      - cptp_qst_physicality.dat        (minimum eigenvalue statistics)
    """
    print("  Generating Experiment 1: Qubit inverse problem...")

    # System parameters
    omega = np.pi
    Omega_drive = 0.3 * np.pi
    gamma1 = 0.35
    gamma_phi = 0.18

    sx, sy, sz = pauli_x(), pauli_y(), pauli_z()
    sm = sigma_minus()
    I2 = identity(2)

    H = 0.5 * omega * sz + 0.5 * Omega_drive * sx
    L1 = sm
    L2 = sz / np.sqrt(2)
    Ls = [L1, L2]
    rates = [gamma1, gamma_phi]

    # Initial state |+><+|
    rho0 = np.array([[0.5, 0.5], [0.5, 0.5]], dtype=np.complex128)

    # Time grid for plots
    T = 5.0
    N_plot = 21
    t_plot = np.linspace(0, T, N_plot)

    # Exact trajectory
    rhos_exact = solve_lindblad_expm(H, Ls, rates, rho0, t_plot)

    # Observables
    def expect(rho, O):
        return np.real(np.trace(O @ rho))

    exact_x = np.array([expect(rhos_exact[i], sx) for i in range(N_plot)])
    exact_y = np.array([expect(rhos_exact[i], sy) for i in range(N_plot)])
    exact_z = np.array([expect(rhos_exact[i], sz) for i in range(N_plot)])

    # Noisy data
    rng = np.random.default_rng(seed)
    noise_std = 0.01
    noisy_x = exact_x + rng.normal(0, noise_std, N_plot)
    noisy_y = exact_y + rng.normal(0, noise_std, N_plot)
    noisy_z = exact_z + rng.normal(0, noise_std, N_plot)

    # --- Train CPTP-Cholesky model and baseline ---
    # Use a simple finite-difference PINN approach with scipy optimizer
    # for reproducibility without heavy torch training

    def cholesky_density_from_params(params_flat, N_t, t_vals):
        """Map flat parameters to density trajectory via Cholesky parametrization.
        Params: for each time point, 4 real values (a_diag1, a_diag2, a_off_re, a_off_im)
        """
        params = params_flat.reshape(N_t, 4)
        rhos = np.zeros((N_t, 2, 2), dtype=np.complex128)
        for i in range(N_t):
            a11 = np.abs(params[i, 0]) + 1e-4
            a22 = np.abs(params[i, 1]) + 1e-4
            a21_re, a21_im = params[i, 2], params[i, 3]
            A = np.array([[a11, 0], [a21_re + 1j * a21_im, a22]], dtype=np.complex128)
            M = A @ A.conj().T
            rhos[i] = M / np.trace(M)
        return rhos

    def bloch_density_from_params(params_flat, N_t, t_vals):
        """Map flat parameters to density trajectory via Bloch parametrization (no PSD guarantee)."""
        params = params_flat.reshape(N_t, 3)
        rhos = np.zeros((N_t, 2, 2), dtype=np.complex128)
        for i in range(N_t):
            rx, ry, rz = params[i]
            rhos[i] = 0.5 * (I2 + rx * sx + ry * sy + rz * sz)
        return rhos

    def fit_trajectory(param_fn, n_params_per_t, t_vals, noisy_obs, H, Ls, rates, rho0, seed_val):
        """Fit a trajectory model using data + physics loss."""
        N_t = len(t_vals)
        rng_init = np.random.default_rng(seed_val)
        x0 = rng_init.normal(0, 0.5, N_t * n_params_per_t)
        dt = t_vals[1] - t_vals[0] if N_t > 1 else 1.0

        def loss_fn(params_flat):
            rhos = param_fn(params_flat, N_t, t_vals)
            # Data loss
            pred_x = np.array([expect(rhos[i], sx) for i in range(N_t)])
            pred_y = np.array([expect(rhos[i], sy) for i in range(N_t)])
            pred_z = np.array([expect(rhos[i], sz) for i in range(N_t)])
            data_loss = (np.sum((pred_x - noisy_obs[0])**2) +
                        np.sum((pred_y - noisy_obs[1])**2) +
                        np.sum((pred_z - noisy_obs[2])**2)) / N_t

            # Physics loss (finite-difference residual)
            phys_loss = 0.0
            for i in range(1, N_t - 1):
                drho_fd = (rhos[i+1] - rhos[i-1]) / (2 * dt)
                drho_lind = lindblad_rhs(rhos[i], H, Ls, rates)
                phys_loss += np.sum(np.abs(drho_fd - drho_lind)**2)
            phys_loss /= max(N_t - 2, 1)

            # IC loss
            ic_loss = np.sum(np.abs(rhos[0] - rho0)**2)

            return 10.0 * data_loss + 1.0 * phys_loss + 100.0 * ic_loss

        result = minimize(loss_fn, x0, method='L-BFGS-B',
                         options={'maxiter': 1000, 'ftol': 1e-12})
        return param_fn(result.x, N_t, t_vals)

    # Fit both models
    noisy_obs = [noisy_x, noisy_y, noisy_z]
    rhos_cptp = fit_trajectory(cholesky_density_from_params, 4, t_plot, noisy_obs,
                               H, Ls, rates, rho0, seed)
    rhos_base = fit_trajectory(bloch_density_from_params, 3, t_plot, noisy_obs,
                               H, Ls, rates, rho0, seed)

    cptp_x = np.array([expect(rhos_cptp[i], sx) for i in range(N_plot)])
    cptp_y = np.array([expect(rhos_cptp[i], sy) for i in range(N_plot)])
    cptp_z = np.array([expect(rhos_cptp[i], sz) for i in range(N_plot)])
    base_x = np.array([expect(rhos_base[i], sx) for i in range(N_plot)])
    base_y = np.array([expect(rhos_base[i], sy) for i in range(N_plot)])
    base_z = np.array([expect(rhos_base[i], sz) for i in range(N_plot)])

    # Write cptp_qst_qubit_observables.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_qubit_observables.dat'), 'w') as f:
        f.write("t exactx cptpx basex exacty cptpy basey exactz cptpz basez\n")
        for i in range(N_plot):
            f.write(f"{t_plot[i]:.10g} {exact_x[i]:.10g} {cptp_x[i]:.10g} {base_x[i]:.10g} "
                    f"{exact_y[i]:.10g} {cptp_y[i]:.10g} {base_y[i]:.10g} "
                    f"{exact_z[i]:.10g} {cptp_z[i]:.10g} {base_z[i]:.10g}\n")

    # Write cptp_qst_qubit_noisy.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_qubit_noisy.dat'), 'w') as f:
        f.write("t nx ny nz\n")
        for i in range(N_plot):
            f.write(f"{t_plot[i]:.10g} {noisy_x[i]:.10g} {noisy_y[i]:.10g} {noisy_z[i]:.10g}\n")

    # --- Multi-seed ablation for sparse observations ---
    obs_fractions = [100, 50, 25]
    seeds_ablation = [42, 137]
    ablation_results = []
    physicality_results = []

    for obs_frac in obs_fractions:
        td_cptp_list, td_base_list = [], []
        mineig_cptp_list, mineig_base_list = [], []

        for s in seeds_ablation:
            rng_s = np.random.default_rng(s)
            # Subsample time points
            n_obs = max(3, int(N_plot * obs_frac / 100))
            obs_idx = np.sort(rng_s.choice(N_plot, n_obs, replace=False))
            obs_idx[0] = 0  # always include t=0

            t_obs = t_plot[obs_idx]
            noisy_x_s = exact_x[obs_idx] + rng_s.normal(0, noise_std, n_obs)
            noisy_y_s = exact_y[obs_idx] + rng_s.normal(0, noise_std, n_obs)
            noisy_z_s = exact_z[obs_idx] + rng_s.normal(0, noise_std, n_obs)
            noisy_obs_s = [noisy_x_s, noisy_y_s, noisy_z_s]

            rhos_cptp_s = fit_trajectory(cholesky_density_from_params, 4, t_obs,
                                         noisy_obs_s, H, Ls, rates, rho0, s)
            rhos_base_s = fit_trajectory(bloch_density_from_params, 3, t_obs,
                                         noisy_obs_s, H, Ls, rates, rho0, s)
            rhos_exact_s = solve_lindblad_expm(H, Ls, rates, rho0, t_obs)

            # Trace distances
            td_cptp = np.mean([0.5 * trace_norm(rhos_cptp_s[i] - rhos_exact_s[i])
                              for i in range(n_obs)])
            td_base = np.mean([0.5 * trace_norm(rhos_base_s[i] - rhos_exact_s[i])
                              for i in range(n_obs)])
            td_cptp_list.append(td_cptp)
            td_base_list.append(td_base)

            # Minimum eigenvalues
            eigs_cptp = [np.min(np.linalg.eigvalsh(rhos_cptp_s[i])) for i in range(n_obs)]
            eigs_base = [np.min(np.linalg.eigvalsh(rhos_base_s[i])) for i in range(n_obs)]
            mineig_cptp_list.append(np.mean(eigs_cptp))
            mineig_base_list.append(np.min(eigs_base))

        ablation_results.append({
            'obs': obs_frac,
            'cptp': np.mean(td_cptp_list),
            'cptpstd': np.std(td_cptp_list),
            'base': np.mean(td_base_list),
            'basestd': np.std(td_base_list),
        })
        physicality_results.append({
            'obs': obs_frac,
            'cptp': np.mean(mineig_cptp_list),
            'cptpmin': np.min(mineig_cptp_list),
            'base': np.mean(mineig_base_list),
            'basemin': np.min(mineig_base_list),
        })

    # Write cptp_qst_sparse_ablation.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_sparse_ablation.dat'), 'w') as f:
        f.write("obs cptp cptpstd base basestd\n")
        for r in ablation_results:
            f.write(f"{r['obs']} {r['cptp']:.10g} {r['cptpstd']:.10g} "
                    f"{r['base']:.10g} {r['basestd']:.10g}\n")

    # Write cptp_qst_physicality.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_physicality.dat'), 'w') as f:
        f.write("obs cptp cptpmin base basemin\n")
        for r in physicality_results:
            f.write(f"{r['obs']} {r['cptp']:.10g} {r['cptpmin']:.10g} "
                    f"{r['base']:.10g} {r['basemin']:.10g}\n")

    print("    Done.")


