def generate_exp4_data(seed=42, n_repeats=5):
    """Generate compiler scaling benchmark data.

    Produces:
      - cptp_qst_compiler_scaling.dat
    """
    print("  Generating Experiment 4: Compiler scaling...")

    rng = np.random.default_rng(seed)
    dims = [2, 4, 8, 16, 24]
    ms = [2, 4, 4, 4, 4]
    results = []

    for d, m in zip(dims, ms):
        # Random system
        A = rng.standard_normal((d, d)) + 1j * rng.standard_normal((d, d))
        H = (A + A.conj().T) / 2
        Ls_local = []
        for _ in range(m):
            L = rng.standard_normal((d, d)) + 1j * rng.standard_normal((d, d))
            L *= 0.1
            Ls_local.append(L)
        rates_local = [1.0] * m

        # Random test state
        B = rng.standard_normal((d, d)) + 1j * rng.standard_normal((d, d))
        rho_test = B @ B.conj().T
        rho_test /= np.trace(rho_test)

        # Dense: build and evaluate
        t0 = time.perf_counter()
        for _ in range(n_repeats):
            L_super = dense_liouvillian(H, Ls_local, rates_local)
            rho_vec = rho_test.flatten(order='F')
            _ = (L_super @ rho_vec).reshape(d, d, order='F')
        dense_total = (time.perf_counter() - t0) / n_repeats

        # Structured: evaluate directly
        t0 = time.perf_counter()
        for _ in range(n_repeats):
            _ = lindblad_rhs(rho_test, H, Ls_local, rates_local)
        struct_total = (time.perf_counter() - t0) / n_repeats

        # Memory (bytes -> MB using 1e6)
        dense_mem_mb = 2 * (d ** 4) * 8 / 1e6
        struct_mem_mb = 2 * (m + 1) * (d ** 2) * 8 / 1e6

        results.append({
            'd': d, 'denseMem': dense_mem_mb, 'structMem': struct_mem_mb,
            'denseMs': dense_total * 1000, 'structMs': struct_total * 1000,
        })
        print(f"    d={d}: dense={dense_total*1000:.4f}ms, struct={struct_total*1000:.4f}ms")

    # Write cptp_qst_compiler_scaling.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_compiler_scaling.dat'), 'w') as f:
        f.write("d denseMem structMem denseMs structMs\n")
        for r in results:
            f.write(f"{r['d']} {r['denseMem']:.6g} {r['structMem']:.6g} "
                    f"{r['denseMs']:.7g} {r['structMs']:.7g}\n")

    print("    Done.")


