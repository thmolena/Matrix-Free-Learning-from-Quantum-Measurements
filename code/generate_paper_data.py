# Shared utilities (no torch dependency for most experiments)
# ============================================================

def pauli_x():
    return np.array([[0, 1], [1, 0]], dtype=np.complex128)

def pauli_y():
    return np.array([[0, -1j], [1j, 0]], dtype=np.complex128)

def pauli_z():
    return np.array([[1, 0], [0, -1]], dtype=np.complex128)

def sigma_minus():
    return np.array([[0, 0], [1, 0]], dtype=np.complex128)

def sigma_plus():
    return np.array([[0, 1], [0, 0]], dtype=np.complex128)

def identity(d):
    return np.eye(d, dtype=np.complex128)


def dense_liouvillian(H, Ls, rates):
    """Build dense d^2 x d^2 Liouvillian (column-major vec convention)."""
    d = H.shape[0]
    I = np.eye(d, dtype=np.complex128)
    L_super = -1j * (np.kron(I, H) - np.kron(H.T, I))
    for L, gamma in zip(Ls, rates):
        Ldag_L = L.conj().T @ L
        L_super += gamma * (
            np.kron(L.conj(), L)
            - 0.5 * np.kron(I, Ldag_L)
            - 0.5 * np.kron(Ldag_L.T, I)
        )
    return L_super


def lindblad_rhs(rho, H, Ls, rates):
    """Evaluate L[rho] directly (structured mode)."""
    drho = -1j * (H @ rho - rho @ H)
    for L, gamma in zip(Ls, rates):
        Ldag_L = L.conj().T @ L
        drho += gamma * (L @ rho @ L.conj().T - 0.5 * (Ldag_L @ rho + rho @ Ldag_L))
    return drho


def solve_lindblad_expm(H, Ls, rates, rho0, t_grid):
    """Solve Lindblad equation via dense matrix exponential."""
    d = H.shape[0]
    L_super = dense_liouvillian(H, Ls, rates)
    rho0_vec = rho0.flatten(order='F')
    rhos = np.zeros((len(t_grid), d, d), dtype=np.complex128)
    for i, t in enumerate(t_grid):
        rho_vec = expm(L_super * t) @ rho0_vec
        rhos[i] = rho_vec.reshape(d, d, order='F')
    return rhos


def trace_norm(A):
    """Trace norm (sum of singular values) for Hermitian matrix."""
    return np.sum(np.abs(np.linalg.eigvalsh(0.5 * (A + A.conj().T))))


