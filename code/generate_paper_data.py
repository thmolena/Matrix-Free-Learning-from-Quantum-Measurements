def generate_exp2_data(seed=42):
    """Generate residual certificate data.

    Produces:
      - cptp_qst_residual_certificate.dat
    """
    print("  Generating Experiment 2: Residual certificate...")

    omega = np.pi
    Omega_drive = 0.3 * np.pi
    gamma1 = 0.35
    gamma_phi = 0.18

    sx, sz = pauli_x(), pauli_z()
    sm = sigma_minus()
    I2 = identity(2)

    H = 0.5 * omega * sz + 0.5 * Omega_drive * sx
    L1 = sm
    L2 = sz / np.sqrt(2)
    Ls = [L1, L2]
    rates = [gamma1, gamma_phi]

    rho0 = np.array([[0.5, 0.5], [0.5, 0.5]], dtype=np.complex128)

    T = 5.0
    N_grid = 601
    t_grid = np.linspace(0, T, N_grid)
    dt = t_grid[1] - t_grid[0]

    # Exact trajectory via matrix exponential
    rhos_exact = solve_lindblad_expm(H, Ls, rates, rho0, t_grid)

    eps_values = [0.01, 0.025, 0.05, 0.1]
    results = []

    for eps in eps_values:
        # Perturbed trajectory
        a_t = eps * np.sin(np.pi * t_grid / T) ** 2
        rhos_pert = np.zeros_like(rhos_exact)
        for i in range(N_grid):
            rhos_pert[i] = (1 - a_t[i]) * rhos_exact[i] + a_t[i] * I2 / 2

        # Derivative via central finite differences
        drho_dt = np.zeros_like(rhos_pert)
        for i in range(1, N_grid - 1):
            drho_dt[i] = (rhos_pert[i + 1] - rhos_pert[i - 1]) / (2 * dt)
        drho_dt[0] = (rhos_pert[1] - rhos_pert[0]) / dt
        drho_dt[-1] = (rhos_pert[-1] - rhos_pert[-2]) / dt

        # Residual trace norms
        residual_trace_norms = np.zeros(N_grid)
        for i in range(N_grid):
            r_i = drho_dt[i] - lindblad_rhs(rhos_pert[i], H, Ls, rates)
            residual_trace_norms[i] = trace_norm(r_i)

        # Actual trace distance
        actual_td = np.zeros(N_grid)
        for i in range(N_grid):
            actual_td[i] = 0.5 * trace_norm(rhos_pert[i] - rhos_exact[i])
        max_td = np.max(actual_td)

        # Certificate: integral of (1/2) ||r(s)||_1 ds
        cumulative_cert = np.zeros(N_grid)
        for i in range(1, N_grid):
            cumulative_cert[i] = cumulative_cert[i - 1] + 0.5 * dt * (
                residual_trace_norms[i - 1] + residual_trace_norms[i]) / 2
        cert = np.max(cumulative_cert)

        results.append({'eps': eps, 'maxTD': max_td, 'cert': cert})

    # Write cptp_qst_residual_certificate.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_residual_certificate.dat'), 'w') as f:
        f.write("eps maxTD cert\n")
        for r in results:
            f.write(f"{r['eps']} {r['maxTD']:.10g} {r['cert']:.10g}\n")

    print("    Done.")


