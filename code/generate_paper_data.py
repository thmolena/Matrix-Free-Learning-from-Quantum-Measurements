# Experiment 3: Qutrit leakage identification
# ============================================================

def generate_exp3_data(seed=42):
    """Generate qutrit leakage data.

    Produces:
      - cptp_qst_qutrit_leakage.dat  (exact & fitted populations)
      - cptp_qst_qutrit_noisy.dat    (noisy population measurements)
    """
    print("  Generating Experiment 3: Qutrit leakage...")

    rng = np.random.default_rng(seed)

    # Cascade decay rates
    gamma_10_true = 0.24
    gamma_21_true = 0.075

    # Analytical population dynamics for cascade |2> -> |1> -> |0>
    # starting from rho0 = |2><2|
    def populations_exact(t, g10, g21):
        p2 = np.exp(-g21 * t)
        if np.abs(g10 - g21) > 1e-10:
            p1 = g21 / (g10 - g21) * (np.exp(-g21 * t) - np.exp(-g10 * t))
        else:
            p1 = g21 * t * np.exp(-g21 * t)
        p0 = 1.0 - p1 - p2
        return p0, p1, p2

    # Time grid for plotting
    T = 10.0
    N_plot = 21
    t_plot = np.linspace(0, T, N_plot)

    # Exact populations
    exact_p0, exact_p1, exact_p2 = [], [], []
    for t in t_plot:
        p0, p1, p2 = populations_exact(t, gamma_10_true, gamma_21_true)
        exact_p0.append(p0)
        exact_p1.append(p1)
        exact_p2.append(p2)
    exact_p0 = np.array(exact_p0)
    exact_p1 = np.array(exact_p1)
    exact_p2 = np.array(exact_p2)

    # Noisy populations (fewer time points)
    N_noisy = 11
    t_noisy = np.linspace(0, T, N_noisy)
    noise_std_pop = 0.005
    noisy_p0, noisy_p1, noisy_p2 = [], [], []
    for t in t_noisy:
        p0, p1, p2 = populations_exact(t, gamma_10_true, gamma_21_true)
        n0 = p0 + rng.normal(0, noise_std_pop)
        n1 = p1 + rng.normal(0, noise_std_pop)
        n2 = p2 + rng.normal(0, noise_std_pop)
        # Clip and renormalize
        n0, n1, n2 = max(0, n0), max(0, n1), max(0, n2)
        s = n0 + n1 + n2
        noisy_p0.append(n0 / s)
        noisy_p1.append(n1 / s)
        noisy_p2.append(n2 / s)
    noisy_p0 = np.array(noisy_p0)
    noisy_p1 = np.array(noisy_p1)
    noisy_p2 = np.array(noisy_p2)

    # Fit rates using softplus-positive nonlinear least squares
    def loss_fit(params):
        g10 = np.log1p(np.exp(params[0]))  # softplus
        g21 = np.log1p(np.exp(params[1]))
        total = 0.0
        for i, t in enumerate(t_noisy):
            p0, p1, p2 = populations_exact(t, g10, g21)
            total += (p0 - noisy_p0[i])**2 + (p1 - noisy_p1[i])**2 + (p2 - noisy_p2[i])**2
        return total

    # Initial guess (inverse softplus of rough estimates)
    x0 = np.array([np.log(np.exp(0.3) - 1), np.log(np.exp(0.1) - 1)])
    result = minimize(loss_fit, x0, method='Nelder-Mead', options={'maxiter': 10000, 'xatol': 1e-10})
    g10_fit = np.log1p(np.exp(result.x[0]))
    g21_fit = np.log1p(np.exp(result.x[1]))

    # Fitted populations on the plot grid
    fit_p0, fit_p1, fit_p2 = [], [], []
    for t in t_plot:
        p0, p1, p2 = populations_exact(t, g10_fit, g21_fit)
        fit_p0.append(p0)
        fit_p1.append(p1)
        fit_p2.append(p2)
    fit_p0 = np.array(fit_p0)
    fit_p1 = np.array(fit_p1)
    fit_p2 = np.array(fit_p2)

    # Write cptp_qst_qutrit_leakage.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_qutrit_leakage.dat'), 'w') as f:
        f.write("t p0 p1 p2 f0 f1 f2\n")
        for i in range(N_plot):
            f.write(f"{t_plot[i]:.10g} {exact_p0[i]:.10g} {exact_p1[i]:.10g} "
                    f"{exact_p2[i]:.10g} {fit_p0[i]:.10g} {fit_p1[i]:.10g} {fit_p2[i]:.10g}\n")

    # Write cptp_qst_qutrit_noisy.dat
    with open(os.path.join(DATA_DIR, 'cptp_qst_qutrit_noisy.dat'), 'w') as f:
        f.write("t n0 n1 n2\n")
        for i in range(N_noisy):
            f.write(f"{t_noisy[i]:.10g} {noisy_p0[i]:.10g} {noisy_p1[i]:.10g} {noisy_p2[i]:.10g}\n")

    print(f"    Fitted rates: gamma_10={g10_fit:.4f} (true {gamma_10_true}), "
          f"gamma_21={g21_fit:.4f} (true {gamma_21_true})")
    print("    Done.")


